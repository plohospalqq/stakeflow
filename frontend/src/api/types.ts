export interface AskStep {
  label: string;
  detail: string;
}

/**
 * Why a prepared example answers: `aiOff` the server has no AI key (503 llm_not_configured),
 * `unavailable` the AI or the read-only database role did not answer (another 503),
 * `offline` there is no server at all (static demo, mocks).
 */
export type AskPreviewReason = 'aiOff' | 'unavailable' | 'offline';

/** What POST /ask returns, field for field (the API's tests check this type against it). */
export interface AskAnswer {
  question: string;
  steps: AskStep[];
  answer: string;
  sql: string;
  durationMs: number;
  columns: string[];
  rows: (string | number | null)[][];
  /** Bars: one per row, with an optional comparison value drawn thinner underneath. */
  chart: { label: string; value: number; previous: number | null }[];
  chartUnit: string;
  chartLegend: { current: string; previous: string | null };
  followUps: string[];
  /** False when the question did not match anything the data (or the preview) can answer. */
  matched: boolean;
}

/** An answer and where it came from: the AI, or a prepared example and why (UI only). */
export interface AskReply extends AskAnswer {
  /** Null for the AI's own answer. */
  preview: AskPreviewReason | null;
}

export interface AskTable {
  name: string;
  description: string;
}
